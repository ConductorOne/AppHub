func auditRegistry(r *recorder, MT tree, sourceRoot string) {
	regAll, regDiscarded := 0, 0
	for _, fl := range MT.files {
		if filepath.Base(fl.path) != "registry.go" {
			continue
		}
		ast.Inspect(fl.f, func(n ast.Node) bool {
			if _, ok := selectorCall(n, "Register"); ok {
				regAll++
			}
			return true
		})
		ast.Inspect(fl.f, func(n ast.Node) bool {
			es, ok := n.(*ast.ExprStmt)
			if !ok {
				return true
			}
			if _, ok := selectorCall(es.X, "Register"); ok {
				regDiscarded++
			}
			return true
		})
	}
	r.emit("E25", ratio(regDiscarded, regAll))

	cmdRoot := filepath.Join(sourceRoot, "cmd")
	entries, err := os.ReadDir(cmdRoot)
	if err != nil {
		fail("E26: cannot read %s: %v", cmdRoot, err)
	}
	cmdDirs, withRegistry := 0, 0
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		cmdDirs++
		sub := mustTree("CMD/"+e.Name(), filepath.Join(cmdRoot, e.Name()), sourceRoot)
		found := false
		for _, fl := range sub.files {
			ast.Inspect(fl.f, func(n ast.Node) bool {
				if _, ok := selectorCall(n, "NewRegistry"); ok {
					found = true
				}
				return true
			})
		}
		if found {
			withRegistry++
		}
	}
	r.emit("E26", ratio(withRegistry, cmdDirs))
}

// ----------------------------------------------------------------- E27 ---

func auditPaved(r *recorder, MT tree) {
	modMethods := map[string]bool{
		"ID": true, "Name": true, "Description": true, "Icon": true,
		"Category": true, "Execute": true, "Validate": true, "Schema": true,
	}
	paved := map[string]bool{}
	sep := string(filepath.Separator)
	for _, fl := range MT.files {
		if !strings.Contains(fl.path, sep+"paved"+sep) {
			continue
		}
		for _, d := range fl.f.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv != nil && fd.Name.IsExported() {
				paved[fd.Name.Name] = true
			}
		}
	}
	matching := 0
	pnames := make([]string, 0, len(paved))
	for k := range paved {
		pnames = append(pnames, k)
		if modMethods[k] {
			matching++
		}
	}
	sort.Strings(pnames)
	r.emit("E27", ratio(matching, len(paved)))
	r.detail("paved exported methods: %s", strings.Join(pnames, " "))
}

// ----------------------------------------------------------------- E28 ---

// auditBoundaryRules derives the one row that is a claim about the target
// repository rather than the source.
//
// E28 counts the import-boundary rules AppHub enforces. No amount of reading
// the source tree can establish it, which is why TargetRoot is a required input
// rather than E28 being exempted from the row set. An exemption is an omission
// with a note attached, and the failure this contract exists for is precisely a
// row that is absent while the table says it is derived.
func auditBoundaryRules(r *recorder, targetRoot string) {
	bt := mustTree("BOUNDARY", filepath.Join(targetRoot, "internal/boundary"), targetRoot)

	var lits []*ast.CompositeLit
	var where []string
	for _, fl := range bt.files {
		ast.Inspect(fl.f, func(n ast.Node) bool {
			kv, ok := n.(*ast.KeyValueExpr)
			if !ok {
				return true
			}
			if k, ok := kv.Key.(*ast.Ident); !ok || k.Name != "Rules" {
				return true
			}
			cl, ok := kv.Value.(*ast.CompositeLit)
			if !ok {
				return true
			}
			lits = append(lits, cl)
			where = append(where, bt.pos(cl))
			return true
		})
	}
	if len(lits) != 1 {
		fail("E28: found %d Rules composite literals under %s (%s); the row counts the "+
			"rule set this repository enforces, and it is only a count if there is exactly "+
			"one place that states it", len(lits), bt.root, strings.Join(where, ", "))
	}

	names := make([]string, 0, len(lits[0].Elts))
	for _, el := range lits[0].Elts {
		cl, ok := el.(*ast.CompositeLit)
		if !ok {
			fail("E28: rule %d in %s is not a composite literal (%T); the rule set cannot "+
				"be enumerated by name", len(names), where[0], el)
		}
		named := ""
		for _, f := range cl.Elts {
			kv, ok := f.(*ast.KeyValueExpr)
			if !ok {
				continue
			}
			if k, ok := kv.Key.(*ast.Ident); !ok || k.Name != "Name" {
				continue
			}
			lit, ok := kv.Value.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				continue
			}
			v, uerr := strconv.Unquote(lit.Value)
			if uerr != nil {
				fail("E28: cannot unquote a rule name in %s (%s): %v", where[0], lit.Value, uerr)
			}
			named = v
		}
		if named == "" {
			fail("E28: rule %d in %s has no string Name; an unnamed rule cannot be "+
				"reported as part of the enforced set", len(names), where[0])
		}
		names = append(names, named)
	}
	sort.Strings(names)
	r.emit("E28", total(len(names)))
	r.detail("derived from %s: %s", where[0], strings.Join(names, " "))
}
