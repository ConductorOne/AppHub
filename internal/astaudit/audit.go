func auditSetters(r *recorder, MT tree, impls []moduleImpl) {
	n := len(impls)
	fields := map[string]bool{}
	setters, setterRecv := 0, map[string]bool{}
	for _, fl := range MT.files {
		for _, d := range fl.f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || fd.Body == nil {
				continue
			}
			if !strings.HasPrefix(fd.Name.Name, "Set") || len(fd.Name.Name) < 4 ||
				fd.Name.Name[3] < 'A' || fd.Name.Name[3] > 'Z' {
				continue
			}
			setters++
			setterRecv[recvType(fd)] = true
			ast.Inspect(fd.Body, func(node ast.Node) bool {
				as, ok := node.(*ast.AssignStmt)
				if !ok {
					return true
				}
				for _, l := range as.Lhs {
					if se, ok := l.(*ast.SelectorExpr); ok {
						fields[se.Sel.Name] = true
					}
				}
				return true
			})
		}
	}
	r.emit("E11", total(setters))
	r.emit("E10", ratio(len(setterRecv), n))

	if len(fields) == 0 {
		fail("E12: no fields derived from %d setter bodies; the guard population would be empty",
			setters)
	}
	fnames := make([]string, 0, len(fields))
	for k := range fields {
		fnames = append(fnames, k)
	}
	sort.Strings(fnames)

	isGuardField := func(e ast.Expr) bool {
		switch x := e.(type) {
		case *ast.SelectorExpr:
			return fields[x.Sel.Name]
		case *ast.Ident:
			return fields[x.Name]
		}
		return false
	}
	guardsAll, guardsReturning := 0, 0
	for _, im := range impls {
		ast.Inspect(im.fd.Body, func(node ast.Node) bool {
			is, ok := node.(*ast.IfStmt)
			if !ok || is.Cond == nil {
				return true
			}
			g := 0
			ast.Inspect(is.Cond, func(m ast.Node) bool {
				if be, ok := m.(*ast.BinaryExpr); ok && be.Op == token.EQL &&
					isNilIdent(be.Y) && isGuardField(be.X) {
					g++
				}
				return true
			})
			if g == 0 {
				return true
			}
			guardsAll += g
			ret := false
			ast.Inspect(is.Body, func(m ast.Node) bool {
				if _, ok := m.(*ast.ReturnStmt); ok {
					ret = true
				}
				return true
			})
			if ret {
				guardsReturning += g
			}
			return true
		})
	}
	r.emit("E12", ratio(guardsReturning, guardsAll))
	r.detail("fields derived from the setter bodies: %s", strings.Join(fnames, " "))

	vTot, vHit := 0, 0
	for _, fl := range MT.files {
		for _, d := range fl.f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || fd.Name.Name != "Validate" || fd.Body == nil {
				continue
			}
			vTot++
			ast.Inspect(fd.Body, func(node ast.Node) bool {
				if _, ok := selectorCall(node, "ValidateDeclaredParams"); ok {
					vHit++
				}
				return true
			})
		}
	}
	r.emit("E13", ratio(vHit, vTot))
}

// ------------------------------------------------------------- E15-E19 ---

func auditImports(r *recorder, MT, SL tree) {
	r.emit("E15", ratio(countImporters(MT, func(p string) bool {
		return strings.Contains(p, "/internal/services")
	}), MT.n()))
	r.emit("E16a", ratio(countImporters(SL, func(p string) bool {
		return strings.HasSuffix(p, "/internal/modules")
	}), SL.n()))
	r.emit("E16b", ratio(countImporters(SL, func(p string) bool {
		return strings.Contains(p, "/internal/modules")
	}), SL.n()))

	// E17 states two figures -- by file and by package -- and is one row, so the
	// two cannot drift apart into a row and a not-quite-row.
	importsDB := func(p string) bool { return strings.HasSuffix(p, "/internal/database") }
	pkgs, pkgsImporting := map[string]bool{}, map[string]bool{}
	for _, fl := range MT.files {
		d := filepath.Dir(fl.path)
		pkgs[d] = true
		if anyImport(fl.f, importsDB) {
			pkgsImporting[d] = true
		}
	}
	r.emit("E17", labelled("files", countImporters(MT, importsDB), MT.n()),
		labelled("packages", len(pkgsImporting), len(pkgs)))

	r.emit("E18", ratio(countImporters(MT, func(p string) bool {
		return strings.HasPrefix(p, "github.com/aws/aws-sdk-go-v2")
	}), MT.n()))

	goStmts := 0
	for _, fl := range MT.files {
		found := false
		ast.Inspect(fl.f, func(n ast.Node) bool {
			if _, ok := n.(*ast.GoStmt); ok {
				found = true
			}
			return true
		})
		if found {
			goStmts++
		}
	}
	r.emit("E19", ratio(goStmts, MT.n()))
}

// ----------------------------------------------------------------- E23 ---

// snakeCase is the form E23 claims of the icon arguments. E23 is a claim about
// the *form* of a string and nothing else: whether an icon name is a member of
// any icon set is not checkable from this source tree, and the row says so
// rather than implying a count it cannot make.
var snakeCase = regexp.MustCompile(`^[a-z][a-z0-9]*(_[a-z0-9]+)*$`)

func auditIcons(r *recorder, MT tree) {
	const iconArg = 3 // NewBaseModule(id, name, description, icon, category)
	pop, matching := 0, 0
	var icons []string
	for _, fl := range MT.files {
		ast.Inspect(fl.f, func(n ast.Node) bool {
			ce, ok := selectorCall(n, "NewBaseModule")
			if !ok || len(ce.Args) <= iconArg {
				return true
			}
			pop++
			lit, ok := ce.Args[iconArg].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				fail("E23: the icon argument at %s is not a string literal (%T); E23 is a "+
					"claim about the lexical form of a literal, so a computed icon is a "+
					"state the row cannot describe and the tool must be edited to say so",
					MT.pos(ce), ce.Args[iconArg])
			}
			v, uerr := strconv.Unquote(lit.Value)
			if uerr != nil {
				fail("E23: cannot unquote the icon argument at %s (%s): %v", MT.pos(ce), lit.Value, uerr)
			}
			icons = append(icons, v)
			if snakeCase.MatchString(v) {
				matching++
			}
			return true
		})
	}
	sort.Strings(icons)
	r.emit("E23", ratio(matching, pop))
	r.detail("icon arguments, lexical form only -- membership of an icon set is not "+
		"checkable here: %s", strings.Join(icons, " "))
}

// ----------------------------------------------------------------- E24 ---

func auditProgress(r *recorder, MT tree) {
	var lit, binx, ident, other, rpTotal int
	for _, fl := range MT.files {
		ast.Inspect(fl.f, func(n ast.Node) bool {
			ce, ok := selectorCall(n, "ReportProgress")
			if !ok || len(ce.Args) < 2 {
				return true
			}
			rpTotal++
			switch a := ce.Args[1].(type) {
			case *ast.BasicLit:
				if a.Kind == token.INT {
					lit++
				} else {
					other++
				}
			case *ast.BinaryExpr:
				binx++
			case *ast.Ident:
				ident++
			default:
				other++
			}
			return true
		})
	}
	if lit+binx+ident+other != rpTotal {
		fail("E24: classified %d of %d calls; the classes must partition the population",
			lit+binx+ident+other, rpTotal)
	}
	// One row, four figures. The row this whole contract was written for is
	// still one row of the table, so the emitted rows and the table's rows map
	// one-to-one without a mapping to maintain.
	r.emit("E24", labelled("integer literals", lit, rpTotal),
		labelled("arithmetic expressions", binx, rpTotal),
		labelled("identifiers", ident, rpTotal),
		labelled("anything else", other, rpTotal))
}

